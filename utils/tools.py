import matplotlib.pyplot as plt

def namespace2dict(config):
    config_dict = vars(config)
    for key, value in config_dict.items():
        if isinstance(value, argparse.Namespace):
            config_dict[key] = namespace2dict(value)
    return config_dict

def dict2namespace(config):
    #声明命名空间
    namespace = argparse.Namespace()
    for key, value in config.items():
        if isinstance(value, dict):
            new_value = dict2namespace(value)
        else:
            new_value = value
        #将参数对添加到命名空间中
        setattr(namespace, key, new_value)
    return namespace

def get_configs(cfg_filepath, args=None):
    print("cfg_filepath : ", cfg_filepath)

    with open(cfg_filepath, 'r') as f:
        config = yaml.load(f, Loader=yaml.FullLoader)

        if args is not None:
            configs = dict2namespace({**config, **vars(args)})
        else:
            configs = dict2namespace({**config})

    return configs

def adjust_learning_rate(optimizer, epoch, args, scale=1):
    # lr = args.learning_rate * (0.2 ** (epoch // 2))
    if args.lradj == 'type1':
        lr_adjust = {epoch: args.learning_rate * (0.5 ** (int(epoch - 1) // scale))}
    elif args.lradj == 'type2':
        lr_adjust = {
            2: 5e-5, 4: 1e-5, 6: 5e-6, 8: 1e-6,
            10: 5e-7, 15: 1e-7, 20: 5e-8
        }
    elif args.lradj == 'type3':
        lr_adjust = {
            4: args.learning_rate * 0.1
        }
    elif args.lradj == 'const':
        lr_adjust = {epoch: args.learning_rate}
    if epoch in lr_adjust.keys():
        lr = lr_adjust[epoch]
        for param_group in optimizer.param_groups:
            param_group['lr'] = lr
        print('Updating learning rate to {}'.format(lr))

